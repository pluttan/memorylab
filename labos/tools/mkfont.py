"""Render GOST Type BU into an 8-bit alpha bitmap font for labos (src/font_gost.h).

Usage: python3.12 tools/mkfont.py FONT.ttf SIZE OUT.h
The header is committed, so building labos does not need the font file.
"""
import sys

from PIL import Image, ImageDraw, ImageFont

CHARS = (
    [chr(c) for c in range(0x20, 0x7f)]
    + [chr(c) for c in range(0x410, 0x450)]
    + list('Ёё«»×–—№°±µ≈≤≥→²³·…')
)


def main():
    path, size, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs, alpha = [], []
    for ch in sorted(set(CHARS)):
        left, top, right, bottom = font.getbbox(ch)
        w, h = max(0, right - left), max(0, bottom - top)
        offset = len(alpha)
        if w and h:
            img = Image.new('L', (w, h), 0)
            ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255)
            alpha.extend(img.tobytes())
        advance = round(font.getlength(ch))
        glyphs.append((ord(ch), advance, w, h, left, top, offset))
    with open(out, 'w', encoding='utf-8') as f:
        f.write(f'// Generated by tools/mkfont.py from {path.split("/")[-1]} at {size} px. Do not edit.\n')
        f.write('#ifndef LABOS_FONT_GOST_H\n#define LABOS_FONT_GOST_H\n\n')
        f.write(f'#define FONT_ASCENT {ascent}\n#define FONT_HEIGHT {ascent + descent}\n')
        f.write(f'#define FONT_GLYPHS {len(glyphs)}\n\n')
        f.write('// code, advance, width, height, left, top (from the line top), offset into font_alpha\n')
        f.write('static const struct { unsigned code; unsigned char advance, w, h; signed char left, top; '
                'unsigned offset; } font_glyphs[FONT_GLYPHS] = {\n')
        for g in glyphs:
            f.write('    {%d, %d, %d, %d, %d, %d, %d},\n' % g)
        f.write('};\n\nstatic const unsigned char font_alpha[] = {\n')
        for i in range(0, len(alpha), 24):
            f.write('    ' + ','.join(str(b) for b in alpha[i:i + 24]) + ',\n')
        f.write('};\n\n#endif\n')
    print(f'{len(glyphs)} glyphs, {len(alpha)} bytes, line {ascent + descent} px')


if __name__ == '__main__':
    main()
